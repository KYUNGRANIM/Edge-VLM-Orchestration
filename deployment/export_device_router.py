#!/usr/bin/env python3
"""Write the trained routers into device code, then check the code decides exactly like the trained models.

    python3 export_device_router.py --policy-dir ../policies --collection <training collection>.jsonl
    python3 export_device_router.py ... --runtime <online_routing_final.jsonl>   # also audit a finished run

Stage 1 (M5_A, C++)  -> ../firmware/router_policy.cpp
Stage 2 (Pi_A, Python) -> ../code/stage2_policy.py
Thresholds are mapped back to raw feature values, so the devices need neither the one-hot encoder nor the
scaler. Nothing is written unless the generated code matches the joblib on every training record (the C++ is
compiled with a three-line Arduino stand-in, so a host C++ compiler is needed). --runtime adds a check that a
finished run followed the policy: generated code vs the decisions the devices logged, and the Stage 2 features
Pi_A logged vs profiling/code/pipeline/common.py recomputed from the same answers.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import joblib
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[0] / "profiling" / "code" / "pipeline"))
from common import read_jsonl, safe_int, stage1_features, stage2_features  # noqa: E402

# C++ for every feature of common.stage1_features, from the fields of M5Stage1RouterInput (router_policy.h)
STAGE1_CPP = {
    "m5a_cat": "in.m5a_cat",
    "m5a_sev": "in.m5a_sev",
    "m5_conf_mean": "(in.m5a_conf + in.m5b_conf + in.m5c_conf) / 3.0",
    "m5_conf_min": "min(in.m5a_conf, min(in.m5b_conf, in.m5c_conf))",
    "m5_sev_range": "max(in.m5a_sev, max(in.m5b_sev, in.m5c_sev)) - min(in.m5a_sev, min(in.m5b_sev, in.m5c_sev))",
    "m5_cat_agree": "majority3(in.m5a_cat, in.m5b_cat, in.m5c_cat)",
    "m5_sev_agree": "majority3(in.m5a_sev, in.m5b_sev, in.m5c_sev)",
}

CPP_TEMPLATE = """\
// Generated by deployment/export_device_router.py from {source}.
// Do not edit by hand: retrain, then regenerate. true = END@M5, false = ESCALATE@Pi.
#include "router_policy.h"

template <typename T>
static double majority3(const T& a, const T& b, const T& c) {{
  if (a == b && b == c) return 1.0;
  if (a == b || a == c || b == c) return 2.0 / 3.0;
  return 1.0 / 3.0;
}}

bool router_stage1_end_m5(const M5Stage1RouterInput& in) {{
{decls}{body}}}
"""

PY_TEMPLATE = '''\
# Generated by deployment/export_device_router.py from {source}.
# Do not edit by hand: retrain, then regenerate.
SOURCE = "{source}"


def end_at_pi(f: dict) -> bool:
    """True = END@Pi, False = ESCALATE@Jetson. f = the Stage 2 features of pi_a_router_server.stage2_features."""
{body}'''

ARDUINO_STANDIN = "#pragma once\n#include <algorithm>\n#include <string>\ntypedef std::string String;\nusing std::max;\nusing std::min;\n"

CPP_HARNESS = """\
#include <iostream>
#include <sstream>
#include "router_policy.h"
int main() {
  std::string line;
  while (std::getline(std::cin, line)) {
    std::stringstream ss(line);
    std::string v[9];
    for (auto& x : v) std::getline(ss, x, '\\t');
    M5Stage1RouterInput in{v[0], v[1], v[2], std::stoi(v[3]), std::stoi(v[4]), std::stoi(v[5]),
                           std::stoi(v[6]), std::stoi(v[7]), std::stoi(v[8])};
    std::cout << router_stage1_end_m5(in) << "\\n";
  }
}
"""


def load_policy(path: Path) -> tuple[dict, str]:
    return joblib.load(path), f"{path.name} sha256:{hashlib.sha256(path.read_bytes()).hexdigest()[:12]}"


def columns(pipe, keys: list[str]) -> list[tuple]:
    """Transformed column -> (key, category) if one-hot, (key, mean, scale) if scaled; ColumnTransformer order."""
    cols: list[tuple] = []
    for name, tr, idx in pipe.named_steps["pre"].transformers_:
        if name == "cat":
            cols += [(keys[i], str(v)) for j, i in enumerate(idx) for v in tr.categories_[j]]
        elif name == "num":
            cols += [(keys[i], float(tr.mean_[j]), float(tr.scale_[j])) for j, i in enumerate(idx)]
    return cols


def rules(policy: dict):
    """The tree as nested (kind, key, value, left, right); leaves are True (END) / False (ESCALATE).
    left is taken when the test holds: key != category, or key <= raw threshold. Same-class subtrees collapse."""
    pipe = policy["model"]
    clf = pipe.named_steps["clf"]
    t, cols = clf.tree_, columns(pipe, policy["feature_keys"])

    def walk(n: int):
        if t.children_left[n] < 0:
            return bool(clf.classes_[int(np.argmax(t.value[n]))] == 1)
        left, right = walk(t.children_left[n]), walk(t.children_right[n])
        if isinstance(left, bool) and left == right:
            return left
        col, thr = cols[t.feature[n]], float(t.threshold[n])
        if len(col) == 2:  # one-hot column is 0/1, split at 0.5: left = not this category
            return ("cat", col[0], col[1], left, right)
        return ("num", col[0], thr * col[2] + col[1], left, right)  # z <= thr  <=>  x <= thr*scale + mean

    return walk(0)


def used_keys(node) -> set[str]:
    return set() if isinstance(node, bool) else {node[1]} | used_keys(node[3]) | used_keys(node[4])


def emit_py(node, ind: str = "    ") -> str:
    if isinstance(node, bool):
        return f"{ind}return {node}\n"
    kind, key, x, left, right = node
    test = f'f["{key}"] != {x!r}' if kind == "cat" else f'f["{key}"] <= {x!r}'
    return f"{ind}if {test}:\n" + emit_py(left, ind + "    ") + emit_py(right, ind)


def emit_cpp(node, ind: str = "  ") -> str:
    if isinstance(node, bool):
        return f"{ind}return {'true' if node else 'false'};\n"
    kind, key, x, left, right = node
    test = f"{key} != {json.dumps(x)}" if kind == "cat" else f"{key} <= {x!r}"
    return f"{ind}if ({test}) {{\n" + emit_cpp(left, ind + "  ") + f"{ind}}}\n" + emit_cpp(right, ind)


def make_cpp(policy: dict, source: str) -> str:
    tree = rules(policy)
    unknown = used_keys(tree) - set(STAGE1_CPP)
    if unknown:
        raise SystemExit(f"Stage 1 tree uses features with no C++ formula: {sorted(unknown)}")
    decls = "".join(f"  const String& {k} = {STAGE1_CPP[k]};\n" if k == "m5a_cat"
                    else f"  const double {k} = {STAGE1_CPP[k]};\n" for k in sorted(used_keys(tree)))
    return CPP_TEMPLATE.format(source=source, decls=decls, body=emit_cpp(tree))


def m5_inputs(m5: dict) -> str:
    """One TSV line of M5Stage1RouterInput fields, coerced the way common.stage1_features coerces them."""
    a, b, c = m5["m5_a"], m5["m5_b"], m5["m5_c"]
    return "\t".join([*(str(x.get("cat") or "") for x in (a, b, c)),
                      *(str(safe_int(x.get(k))) for k in ("sev", "conf") for x in (a, b, c))])


def run_cpp(cpp: str, header: Path, lines: list[str]) -> list[bool]:
    with tempfile.TemporaryDirectory() as d:
        d = Path(d)
        (d / "Arduino.h").write_text(ARDUINO_STANDIN)
        (d / "router_policy.h").write_text(header.read_text())
        (d / "router_policy.cpp").write_text(cpp)
        (d / "harness.cpp").write_text(CPP_HARNESS)
        subprocess.run(["c++", "-std=c++17", "-Wall", "-I", str(d), str(d / "router_policy.cpp"),
                        str(d / "harness.cpp"), "-o", str(d / "harness")], check=True)
        out = subprocess.run([str(d / "harness")], input="\n".join(lines) + "\n", capture_output=True,
                             text=True, check=True).stdout.split()
    return [x == "1" for x in out]


def load_py(code: str):
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "stage2_policy.py"
        p.write_text(code)
        spec = importlib.util.spec_from_file_location("stage2_policy_check", p)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
    return mod


def joblib_end(policy: dict, feats: list[dict]) -> list[bool]:
    keys = policy["feature_keys"]
    return [bool(p == 1) for p in policy["model"].predict([[f[k] for k in keys] for f in feats])]


def feats_equal(a: dict, b: dict) -> bool:
    return a.keys() == b.keys() and all(a[k] == b[k] if isinstance(a[k], str) else np.isclose(a[k], b[k]) for k in a)


def same(name: str, got: list, want: list) -> bool:
    n_bad = sum(g != w for g, w in zip(got, want))
    ok = len(got) == len(want) and n_bad == 0
    print(f"  {'OK ' if ok else 'BAD'} {name}: {len(want) - n_bad}/{len(want)} same")
    return ok


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--policy-dir", type=Path, default=HERE / "routers")
    ap.add_argument("--collection", type=Path, required=True, help="the records the policies were trained on")
    ap.add_argument("--runtime", type=Path, help="online_routing_final.jsonl of a finished run to audit")
    ap.add_argument("--out-cpp", type=Path, default=HERE / "m5_firmware" / "router_policy.cpp")
    ap.add_argument("--out-py", type=Path, default=HERE / "servers" / "stage2_policy.py")
    args = ap.parse_args()

    s1, s1_src = load_policy(args.policy_dir / "stage1_m5_router.joblib")
    s2, s2_src = load_policy(args.policy_dir / "stage2_pi_router.joblib")
    cpp, py = make_cpp(s1, s1_src), PY_TEMPLATE.format(source=s2_src, body=emit_py(rules(s2)))
    header = HERE / "m5_firmware" / "router_policy.h"
    stage2 = load_py(py)

    recs = read_jsonl(args.collection)
    with_pi = [r for r in recs if r.get("pi_a") and r.get("pi_b")]
    print(f"training records: {len(recs)} (with Pi answers: {len(with_pi)})")
    ok = same("Stage 1 C++ vs joblib", run_cpp(cpp, header, [m5_inputs(r) for r in recs]),
              joblib_end(s1, [stage1_features(r) for r in recs]))
    f2 = [stage2_features(r) for r in with_pi]
    ok &= same("Stage 2 Python vs joblib", [stage2.end_at_pi(f) for f in f2], joblib_end(s2, f2))

    if args.runtime:
        run = [r for r in read_jsonl(args.runtime) if r.get("status") == "ok"]
        print(f"run records: {len(run)}")
        ok &= same("Stage 1 C++ vs M5_A decision", run_cpp(cpp, header, [m5_inputs(r["m5"]) for r in run]),
                   [r["stage1"]["decision"] == "END@M5" for r in run])
        s2_run = [r for r in run if (r.get("stage2") or {}).get("features")]
        ok &= same("Stage 2 Python vs Pi_A decision", [stage2.end_at_pi(r["stage2"]["features"]) for r in s2_run],
                   [r["stage2"]["decision"] == "END@Pi" for r in s2_run])
        match = [feats_equal(stage2_features(r), r["stage2"]["features"]) for r in s2_run]
        ok &= same("Stage 2 features Pi_A logged vs recomputed", match, [True] * len(match))
        if not all(match):
            print("    e.g.", [r["image_id"] for r, m in zip(s2_run, match) if not m][:5])

    if not ok:
        print("Not written: the generated code does not match.")
        return 1
    args.out_cpp.write_text(cpp)
    args.out_py.write_text(py)
    print(f"wrote {args.out_cpp}\nwrote {args.out_py}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
